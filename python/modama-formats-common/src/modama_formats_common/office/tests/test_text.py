MIB = 1 << 20


def noise_png(path: Path, side: int) -> Path:
    """A PNG of random pixels, side x side: it does not compress (3 bytes a pixel)."""
    Image.frombytes("RGB", (side, side), os.urandom(side * side * 3)).save(path)
    return path


def one(ct, tree: Path):
    (d,) = crawled(ct, tree)
    return d


def word_tree(tmp_path: Path, build, name="doc.docx") -> Path:
    """A tree with one .docx that build(Document) fills, written by python-docx."""
    tree = tmp_path / "tree"
    tree.mkdir(parents=True, exist_ok=True)
    doc = Document()
    doc.core_properties.comments = ""  # the template's "generated by python-docx"
    build(doc)
    doc.save(tree / name)
    return tree


