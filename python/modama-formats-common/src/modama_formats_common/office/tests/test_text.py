def test_title_headings_a_list_and_a_table(collection_tests, tmp_path):
    def build(d):
        d.add_heading("Lamella preparation", 0)
        d.add_heading("Milling", 1)
        p = d.add_paragraph("Thinning at ")
        p.add_run("30 kV").bold = True
        d.add_paragraph("first step", style="List Bullet")
        d.add_paragraph("second step", style="List Bullet")
        t = d.add_table(rows=2, cols=2)
        t.cell(0, 0).text, t.cell(0, 1).text = "Step", "Current"
        t.cell(1, 0).text, t.cell(1, 1).text = "rough", "1 nA"

    text = one(collection_tests, word_tree(tmp_path, build)).extracted.values["text"]
    lines = text.splitlines()
    assert lines[0] == "# Lamella preparation"
    assert "# Milling" in lines
    assert "Thinning at **30 kV**" in lines
    assert "* first step" in lines and "* second step" in lines
    assert "| Step | Current |" in lines and "| rough | 1 nA |" in lines


