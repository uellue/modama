def test_tracked_changes_as_accepted(collection_tests, tmp_path):
    para = (
        b'<w:p><w:r><w:t xml:space="preserve">Kept </w:t></w:r>'
        b'<w:ins w:id="90" w:author="A" w:date="2026-01-01T00:00:00Z">'
        b"<w:r><w:t>INSERTED</w:t></w:r></w:ins>"
        b'<w:del w:id="91" w:author="A" w:date="2026-01-01T00:00:00Z">'
        b"<w:r><w:delText>DELETED</w:delText></w:r></w:del></w:p>"
    )
    repacked(
        FIXTURES / "word_docx" / "testWORD_custom_props.docx",
        tmp_path / "tree" / "tracked.docx",
        "word/document.xml",
        lambda data: data.replace(b"<w:body>", b"<w:body>" + para, 1),
    )
    text = one(collection_tests, tmp_path / "tree").extracted.values["text"]
    assert "Kept INSERTED" in text.splitlines()
    assert "DELETED" not in text


