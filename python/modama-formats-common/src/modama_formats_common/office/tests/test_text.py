# A long rendering is shortened


def test_a_long_document(collection_tests, tmp_path):
    def build(d):
        for i in range(1, 301):
            d.add_paragraph(f"Paragraph {i}.".ljust(60, "x"))

    text = one(collection_tests, word_tree(tmp_path, build)).extracted.values["text"]
    assert text.startswith("Paragraph 1.")
    assert text.rstrip("x").endswith("Paragraph 300.")
    (gap,) = [line for line in text.splitlines() if line.startswith("… ")]
    assert gap.endswith(" bytes left out …")
    assert len(text) <= 4096


